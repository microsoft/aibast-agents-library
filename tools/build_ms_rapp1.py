#!/usr/bin/env python3
"""Build the ms-rapp/1 Step API description from the example Steps.

usage: python tools/build_ms_rapp1.py --write | --check

Each Step in docs/ms-rapp1/steps/ is a rapp/1 agent with two ms-rapp/1 fields, ROUTE and RESULT_SCHEMA. This
script loads every Step, checks it against the profile, and renders docs/ms-rapp1/openapi.json: one operation per
Step at POST /api/lens/<ROUTE>, whose request body is the agent's own parameters schema and whose response is
{"frame": RESULT_SCHEMA}. A Microsoft Foundry agent can take that file as an OpenAPI tool unchanged.
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
STEPS = ROOT / "docs" / "ms-rapp1" / "steps"
OPENAPI = ROOT / "docs" / "ms-rapp1" / "openapi.json"
KERNEL_AGENTS = ROOT / "rapp_brainstem" / "agents"
ROUTE_RE = re.compile(r"^[a-z0-9-]{1,40}$")


class ProfileError(ValueError):
    pass


def load_step(path: Path):
    """Import a Step the way a Brainstem does: the kernel's basic_agent on the path, one module per file."""
    # Bind the kernel's own basic_agent under both names a Step may import, for this load only, so another
    # module already cached as basic_agent (another tier's copy) cannot stand in for the kernel's contract.
    kernel_spec = importlib.util.spec_from_file_location("basic_agent", KERNEL_AGENTS / "basic_agent.py")
    kernel = importlib.util.module_from_spec(kernel_spec)
    kernel_spec.loader.exec_module(kernel)
    saved = {name: sys.modules.get(name) for name in ("basic_agent", "agents.basic_agent")}
    sys.modules["basic_agent"] = sys.modules["agents.basic_agent"] = kernel
    try:
        spec = importlib.util.spec_from_file_location("ms_rapp1_step_" + path.stem, path)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
    finally:
        for name, value in saved.items():
            if value is None:
                sys.modules.pop(name, None)
            else:
                sys.modules[name] = value
    BasicAgent = kernel.BasicAgent

    agents = [obj for obj in vars(module).values()
              if isinstance(obj, type) and issubclass(obj, BasicAgent) and obj is not BasicAgent]
    if len(agents) != 1:
        raise ProfileError(f"{path.name}: needs exactly one BasicAgent subclass, found {len(agents)}")
    return module, agents[0]()


def check(module, agent, path: Path) -> None:
    problems = []
    if not path.name.endswith("_agent.py"):
        problems.append("file name must end in _agent.py so a Brainstem discovers it")
    route = getattr(module, "ROUTE", None)
    if not isinstance(route, str) or not ROUTE_RE.match(route):
        problems.append("ROUTE must be 1-40 lowercase letters, digits or hyphens")
    if not isinstance(getattr(module, "RESULT_SCHEMA", None), dict):
        problems.append("RESULT_SCHEMA must be a JSON schema object")
    meta = getattr(agent, "metadata", {})
    if meta.get("name") != agent.name or not meta.get("description"):
        problems.append("metadata needs the agent's name and a description")
    if (meta.get("parameters") or {}).get("type") != "object":
        problems.append("metadata.parameters must be an object schema")
    if problems:
        raise ProfileError(f"{path.name}: " + "; ".join(problems))


def steps():
    found = []
    for path in sorted(STEPS.glob("*_agent.py")):
        module, agent = load_step(path)
        check(module, agent, path)
        found.append((module, agent))
    if not found:
        raise ProfileError("no Steps found")
    return found


def render() -> str:
    paths = {}
    for module, agent in steps():
        paths["/api/lens/" + module.ROUTE] = {"post": {
            "operationId": agent.name,
            "summary": agent.metadata["description"],
            "requestBody": {"required": True, "content": {"application/json": {
                "schema": agent.metadata["parameters"]}}},
            "responses": {
                "200": {"description": "The Step's checked result.", "content": {"application/json": {"schema": {
                    "type": "object", "properties": {"frame": module.RESULT_SCHEMA}, "required": ["frame"]}}}},
                "400": {"description": "The request was not valid for this Step."},
                "503": {"description": "The Step is not available right now."},
            },
        }}
    doc = {
        "openapi": "3.0.3",
        "info": {"title": "ms-rapp/1 Step API", "version": "1.0.0",
                 "description": "One operation per Step in the catalog. Generated by tools/build_ms_rapp1.py."},
        "servers": [{"url": "https://your-rapp-runtime.example.com"}],
        "paths": paths,
    }
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    try:
        text = render()
    except ProfileError as exc:
        print(f"ms-rapp/1: {exc}", file=sys.stderr)
        return 1
    if args.write:
        OPENAPI.write_text(text, encoding="utf-8")
        print(f"wrote {OPENAPI.relative_to(ROOT)}")
        return 0
    if not OPENAPI.exists() or OPENAPI.read_text(encoding="utf-8") != text:
        print("ms-rapp/1: docs/ms-rapp1/openapi.json is stale; run tools/build_ms_rapp1.py --write", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
